"""Tests for kobopatcher.patchlib._armasm (port of Go rsc.io/arm/armasm).

* test_decode_txt: port of armasm's decode_test.go (TestDecode) over its
  testdata/decode.txt (tests/testdata/armasm_cases_decode.txt; all cases are
  ARM mode, GNU syntax).
* test_go_fixture: ~20k words with the canonical output of Go's Decode
  (Op, Len, Enc, %T/%#v of every Arg, Inst.String(), GNUSyntax, %+q),
  generated by tools/parity/armasm_diff.py.  It covers every reachable
  instFormat, the .plt sections of the firmware corpora and random words.
"""

