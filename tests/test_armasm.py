def test_decode_txt():
    # Port of TestDecode (decode_test.go).
    all_ = (TESTDATA / "armasm_cases_decode.txt").read_text()
    while "\t\t" in all_:
        all_ = all_.replace("\t\t", "\t")
    errors = []
    n = 0
    for line in all_.split("\n"):
        line = line.strip()
        if line == "" or line.startswith("#"):
            continue
        f = line.split("\t", 3)
        i = f[0].find("|")
        assert i >= 0, f"parsing {f[0]!r}: missing | separator"
        assert i % 2 == 0, f"parsing {f[0]!r}: misaligned | separator"
        size = i // 2
        code = bytes.fromhex(f[0][:i] + f[0][i + 1:])
        mode = int(f[1])
        syntax, asm = f[2], f[3]
        assert syntax == "gnu", f"unknown syntax {syntax!r}"  # plan9 syntax is not ported
        try:
            inst = decode(code, Mode(mode))
            out = GNUSyntax(inst)
            length = inst.Len
        except DecodeError as e:
            out = "error: " + str(e)
            length = 0
        if out != asm or length != size:
            errors.append(f"Decode({f[0]}) [{syntax}] = {out}, {length}, want {asm}, {size}")
        n += 1
    assert n == 306
    assert not errors, "\n".join(errors)


def _fixture_lines():
    with gzip.open(TESTDATA / "armasm_cases.txt.gz", "rt") as fh:
        for line in fh:
            line = line.rstrip("\n")
            if line and not line.startswith("#"):
                yield line


def test_go_fixture():
    n = 0
    bad = []
    for want in _fixture_lines():
        hexbytes = want.split("\t", 1)[0]
        got = canonical(hexbytes)
        if got != want:
            bad.append(f"go: {want}\npy: {got}")
        n += 1
    assert n >= 19000
    assert not bad, f"{len(bad)} mismatches:\n" + "\n".join(bad[:20])


def test_modes_and_errors():
    word = bytes.fromhex("04402de5")
    with pytest.raises(DecodeError, match="^unsupported execution mode$"):
        decode(word, ModeThumb)
    with pytest.raises(DecodeError, match="^unsupported execution mode$"):
        decode(word, Mode(0))
    for short in (b"", b"\x00", b"\x78\x47", b"\x00\x00\x00"):
        with pytest.raises(DecodeError, match="^truncated instruction$"):
            decode(short, ModeARM)
    with pytest.raises(DecodeError, match="^unknown instruction$"):
        decode(bytes.fromhex("6b5721d3"), ModeARM)
    # Thumb "bx pc; mov r8, r8" (kobopatch's PLT tail-call stub) is not ARM.
    with pytest.raises(DecodeError):
        decode(b"\x78\x47\xc0\x46", ModeARM)
    assert str(ModeARM) == "ARM" and str(ModeThumb) == "Thumb" and str(Mode(7)) == "Mode(7)"


def test_plt_entry():
    # A typical ARM PLT entry, as walked by kobopatch's decplt.
    buf = memoryview(bytes.fromhex("00c68fe2" "12ca8ce2" "a4f8bce5" "ffffffff"))
    t0 = decode(buf, ModeARM)
    t1 = decode(buf[4:], ModeARM)
    t2 = decode(buf[8:], ModeARM)
    assert t0.Op == ADD and t0.Op == Op.ADD and t1.Op == ADD and t2.Op == LDR == Op.LDR
    assert (t0.Len, t1.Len, t2.Len) == (4, 4, 4)
    assert str(t0) == "ADD R12, PC, #0x0, 12"
    assert str(t1) == "ADD R12, R12, #0x12000"
    assert str(t2) == "LDR PC, [R12, #2212]!"
    assert t0.Args[0] == armasm.R12 and type(t0.Args[0]) is Reg
    assert t0.Args[1] == armasm.PC
    # "add ip, pc, #0, 12" decodes as ImmAlt (the constant could rotate less).
    assert t0.Args[2] == ImmAlt(0, 12) and t0.Args[2].Imm() == Imm(0)
    assert type(t1.Args[2]) is Imm and t1.Args[2] == 0x12000
    assert t0.Args[3] is None
    m = t2.Args[1]
    assert type(m) is Mem
    assert (m.Base, m.Mode, m.Sign, m.Offset) == (armasm.R12, AddrPreIndex, 0, 2212)
    assert armasm.quote_insts([t0, t1, t2]) == (
        '["ADD R12, PC, #0x0, 12" "ADD R12, R12, #0x12000" "LDR PC, [R12, #2212]!"]')
    with pytest.raises(DecodeError):
        decode(buf[12:], ModeARM)


def test_arg_types():
    # ImmAlt: ADD R12, R12, #0x...: v=4, rot=30 (could rotate less).
    t = decode((0xE28CCF04).to_bytes(4, "little"), ModeARM)
    alt = t.Args[2]
    assert type(alt) is ImmAlt and (alt.Val, alt.Rot) == (4, 30)
    assert alt.Imm() == Imm(16) and type(alt.Imm()) is Imm
    assert str(t) == "ADD R12, R12, #0x4, 30"
    assert ImmAlt(1, 0).Imm() == 1  # Go: v<<32 == 0
    # Post-indexed LDR with shifted register.
    t = decode((0xE69CF103).to_bytes(4, "little"), ModeARM)
    m = t.Args[1]
    assert m.Mode == AddrPostIndex and m.Sign == 1 and m.Index == armasm.R3
    assert m.Shift == ShiftLeft and m.Count == 2
    assert armasm.gosyntax(m) == (
        "armasm.Mem{Base:0xc, Mode:0x1, Sign:1, Index:0x3, Shift:0x0, Count:0x2, Offset:0}")
    # Offset addressing.
    t = decode((0xE59CF004).to_bytes(4, "little"), ModeARM)
    assert t.Args[1].Mode == AddrOffset and str(t) == "LDR PC, [R12, #4]"
    # Branch: PCRel.
    t = decode((0xEBFFFFFE).to_bytes(4, "little"), ModeARM)
    assert type(t.Args[0]) is PCRel and t.Args[0] == -8 and str(t) == "BL PC-0x8"
    assert armasm.gosyntax(t.Args[0]) == "-8"
    # Register shift and register list.
    t = decode(bytes.fromhex("0793eab0"), ModeARM)
    assert type(t.Args[2]) is RegShift and str(t) == "RSC.LT R9, R10, R7 LSL #6"
    t = decode(bytes.fromhex("04402de5"), ModeARM)
    assert type(t.Args[0]) is RegList and str(t.Args[0]) == "{R4}" and armasm.gosyntax(t.Args[0]) == "0x10"


def test_go_interface_equality():
    # Go: Arg(Imm(12)) != armasm.R12; Python must not say they are equal.
    assert Imm(12) != armasm.R12
    assert not (Imm(12) == armasm.R12)
    assert armasm.R12 == Reg(12) == 12
    assert {armasm.PC: 0, armasm.R12: 0}[Reg(15)] == 0
    assert Op.ADD == ADD and str(Op.ADD) == "ADD" and str(Op(0)) == "Op(0)"
    assert str(Op(100000)) == "Op(100000)"
    assert f"{Op.LDR}" == "LDR" and f"{armasm.SP}" == "SP" and f"{armasm.R12:d}" == "12"


def test_module_layout():
    # Op constants exist under both armasm.X and Op.X with Go's names.
    tables = importlib.import_module("kobopatcher.patchlib._armasm.tables")
    assert len(tables.OP_NAMES) > 4000
    for name in ("ADD", "LDR", "ADD_EQ", "LDR_ZZ", "BKPT", "VMOV_F64", "UNDEF"):
        assert getattr(armasm, name) == getattr(Op, name)
    assert (REPO / "src/kobopatcher/patchlib/_armasm/LICENSE").read_text().startswith(
        "Copyright (c) 2009 The Go Authors.")


def test_tables_up_to_date():
    # Regenerate tables.py from the Go module cache if it is available.
    gen = REPO / "tools" / "gen_armasm_tables.py"
    spec = importlib.util.spec_from_file_location("gen_armasm_tables", gen)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    src = mod.default_armasm_dir()
    if not (src / "tables.go").exists():
        pytest.skip("rsc.io/arm armasm sources not in the Go module cache")
    res = subprocess.run([sys.executable, str(gen), "--armasm", str(src), "--check"])
    assert res.returncode == 0, "tables.py is out of date; run tools/gen_armasm_tables.py"


def test_decode_speed():
    # ~200k words should take only a few seconds (Go-faithful linear table
    # scan with a candidate cache).
    import random
    import time

    rng = random.Random(1)
    buf = memoryview(rng.randbytes(4 * 50_000))
    t = time.perf_counter()
    for off in range(0, len(buf), 4):
        try:
            decode(buf[off:off + 4], ModeARM)
        except DecodeError:
            pass
    assert time.perf_counter() - t < 5.0
